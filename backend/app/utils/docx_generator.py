from docx.oxml import OxmlElement
from docx.oxml.ns import qn

def set_cell_background(cell, hex_color: str):
    """Sets background shading of a docx table cell."""
    tc_pr = cell._tc.get_or_add_tcPr()
    shd = OxmlElement('w:shd')
    shd.set(qn('w:val'), 'clear')
    shd.set(qn('w:color'), 'auto')
    shd.set(qn('w:fill'), hex_color.replace('#', ''))
    tc_pr.append(shd)

def set_cell_margins(cell, top=100, bottom=100, left=150, right=150):
    """Sets internal cell margins in twips (1 pt = 20 twips)."""
    tc_pr = cell._tc.get_or_add_tcPr()
    tc_mar = OxmlElement('w:tcMar')
    for margin_name, val in [('w:top', top), ('w:bottom', bottom), ('w:left', left), ('w:right', right)]:
        node = OxmlElement(margin_name)
        node.set(qn('w:w'), str(val))
        node.set(qn('w:type'), 'dxa')
        tc_mar.append(node)
    tc_pr.append(tc_mar)

def add_styled_paragraph(doc, text: str, style_name: str = 'Normal', space_after: int = 4, is_bold: bool = False):
    p = doc.add_paragraph(style=style_name)
    p.paragraph_format.space_after = Pt(space_after)
    p.paragraph_format.line_spacing = 1.15
    
    # Parse bold / italics inside text
    # Clean up markdown formatting into runs
    parts = re.split(r'(\*\*.*?\*\*|\*.*?\*|`.*?`)', text)
    for part in parts:
        if not part:
            continue
        if part.startswith('**') and part.endswith('**'):
            run = p.add_run(part[2:-2])
            run.bold = True
        elif part.startswith('*') and part.endswith('*'):
            run = p.add_run(part[1:-1])
            run.italic = True
        elif part.startswith('`') and part.endswith('`'):
            run = p.add_run(part[1:-1])
            run.font.name = 'Consolas'
            run.font.size = Pt(9.5)
            run.font.color.rgb = RGBColor(15, 23, 42)
        else:
            run = p.add_run(part)
            if is_bold:
                run.bold = True
    return p


def strip_outer_markdown_fences(text: str) -> str:
    """Safely strips artificial markdown code block wrappers (e.g. ```markdown ... ``` or dangling ```)."""
    if not text:
        return ""
    lines = text.splitlines()
    while lines and (re.match(r"^```(?:markdown|md|text|txt)?\s*$", lines[0].strip(), re.IGNORECASE) or not lines[0].strip()):
        lines.pop(0)
    while lines and (re.match(r"^```\s*$", lines[-1].strip()) or not lines[-1].strip()):
        lines.pop()
    return "\n".join(lines).strip()


def markdown_to_docx(
    markdown_content: str,
    title: str = "Document Deliverable",
    output_filename: Optional[str] = None,
    output_dir: Optional[Path] = None,
) -> Tuple[str, Path]:
    """
    Compiles markdown content into a publication-grade Microsoft Word (.docx) document.
    Returns (docx_url, physical_path).
    """
    if not output_dir:
        output_dir = Path(__file__).resolve().parent.parent.parent / "uploads" / "generated"
    output_dir.mkdir(parents=True, exist_ok=True)

    # Strip any lines containing AI branding or pipeline watermarks from content
    clean_lines_list = []
    for l in markdown_content.split('\n'):
        l_lower = l.lower().strip()
        if any(brand in l_lower for brand in [
            "omnitask", "omniitask", "omni task", "omni agent",
            "multi-agent swarm", "multi-agent engine", "multi-agent",
            "autonomous code specialist", "autonomous auditing specialist", "autonomous summarizer specialist",
            "prepared by omni", "prepared by: omni", "prepared by omnitask", "prepared by omniitask",
            "prepared by:", "author: omni", "created by omni",
            "generated by omni", "generated by omnitask", "generated by omniitask",
            "official deliverable", "verified document deliverable",
            "publication-grade word document compilation", "publication-grade pdf document compilation",
            "publication-grade document compilation", "word document compilation", "pdf document compilation"
        ]):
            continue
        clean_lines_list.append(l)
    markdown_content = strip_outer_markdown_fences('\n'.join(clean_lines_list))

    # Derive clean title if generic or pipeline title was provided
    if not title or any(b in title.lower() for b in ["omnitask", "compilation", "sub-task", "document deliverable", "deliverable"]):
        m_h = re.search(r'^\s*#\s+(.+)$', markdown_content, re.MULTILINE)
        if m_h:
            cand = re.sub(r'[*_`]', '', m_h.group(1)).strip()
            if not any(b in cand.lower() for b in ["omnitask", "compilation", "deliverable"]):
                title = cand
            else:
                title = "Technical Document"
        else:
            title = "Technical Document"

    if not output_filename:
        safe_base = re.sub(r"[^a-zA-Z0-9_-]", "_", title.lower()).strip("_")[:40] or "document"
        unique_suffix = uuid.uuid4().hex[:8]
        output_filename = f"{safe_base}_{unique_suffix}.docx"

    if not output_filename.endswith(".docx"):
        output_filename += ".docx"

    file_path = output_dir / output_filename

    doc = docx.Document()

    # Set page margins (1 inch all around)
    for section in doc.sections:
        section.top_margin = Inches(1)
        section.bottom_margin = Inches(1)
        section.left_margin = Inches(1)
        section.right_margin = Inches(1)
        
        # Header & Footer (clean, professional, unbranded)
        header = section.header
        hp = header.paragraphs[0]
        hp.text = ""

        footer = section.footer
        fp = footer.paragraphs[0]
        fp.text = ""

    # Document Title Banner (Clean typography without AI branding subtitles)
    title_p = doc.add_paragraph()
    title_p.paragraph_format.space_before = Pt(0)
    title_p.paragraph_format.space_after = Pt(12)
    t_run = title_p.add_run(title)
    t_run.font.name = 'Calibri'
    t_run.font.size = Pt(22)
    t_run.bold = True
    t_run.font.color.rgb = RGBColor(30, 58, 138)  # Deep Navy

    # Process markdown lines (remove duplicate leading heading matching title)
    lines = markdown_content.split('\n')
    for idx, l in enumerate(lines):
        if l.strip():
            m_lead_h = re.match(r'^#\s+(.+)$', l.strip())
            if m_lead_h:
                lead_text = re.sub(r'[*_`]', '', m_lead_h.group(1)).strip()
                if lead_text.lower() == title.lower() or title.lower() in lead_text.lower() or lead_text.lower() in title.lower():
                    lines[idx] = ""
            break

    in_code_block = False
    code_lines = []
    code_block_lang = ""

    i = 0
    while i < len(lines):
        line = lines[i]
        stripped = line.strip()

        # Code block fence
        if stripped.startswith("```"):
            if in_code_block:
                in_code_block = False
                is_md_block = code_block_lang in ["markdown", "md"] or any(l.strip().startswith(("#", "##", "- ", "* ", "1.")) for l in code_lines[:6])
                if is_md_block:
                    # Unpack markdown lines into the main stream to be rendered as styled headings and text
                    lines = lines[:i] + code_lines + lines[i+1:]
                    code_lines = []
                    continue

                if code_lines:
                    # Render code block in a shaded 1-cell table
                    tbl = doc.add_table(rows=1, cols=1)
                    tbl.alignment = WD_TABLE_ALIGNMENT.CENTER
                    cell = tbl.cell(0, 0)
                    cell.width = Inches(6.5)
                    set_cell_background(cell, "F8FAFC")
                    set_cell_margins(cell, top=120, bottom=120, left=180, right=180)
                    
                    cp = cell.paragraphs[0]
                    cp.paragraph_format.space_after = Pt(0)
                    c_run = cp.add_run("\n".join(code_lines))
                    c_run.font.name = 'Consolas'
                    c_run.font.size = Pt(9.0)
                    c_run.font.color.rgb = RGBColor(15, 23, 42)
                    
                    p_spacer = doc.add_paragraph()
                    p_spacer.paragraph_format.space_after = Pt(4)
                code_lines = []
            else:
                code_block_lang = stripped[3:].strip().lower()
                in_code_block = True
                code_lines = []
            i += 1
            continue

        if in_code_block:
            code_lines.append(line)
            i += 1
            continue

        if not stripped:
            i += 1
            continue

        # Horizontal Rule
        if stripped in ["---", "***", "___"]:
            hr_p = doc.add_paragraph()
            hr_p.paragraph_format.space_after = Pt(6)
            hr_run = hr_p.add_run("―" * 45)
            hr_run.font.color.rgb = RGBColor(226, 232, 240)
            i += 1
            continue

        # Markdown Headings: H1 (#), H2 (##), H3 (###), H4 (####), H5 (#####)
        h_match = re.match(r'^(#{1,6})\s+(.*)$', stripped)
        if h_match:
            level = len(h_match.group(1))
            heading_text = h_match.group(2).strip()
            
            # Clean any internal formatting hashes or quotes
            heading_text = re.sub(r'[*_`]', '', heading_text)

            hp = doc.add_paragraph()
            hp.paragraph_format.keep_with_next = True
            
            if level == 1:
                hp.paragraph_format.space_before = Pt(14)
                hp.paragraph_format.space_after = Pt(6)
                hrun = hp.add_run(heading_text)
                hrun.font.name = 'Calibri'
                hrun.font.size = Pt(16)
                hrun.bold = True
                hrun.font.color.rgb = RGBColor(30, 41, 59)
            elif level == 2:
                hp.paragraph_format.space_before = Pt(12)
                hp.paragraph_format.space_after = Pt(5)
                hrun = hp.add_run(heading_text)
                hrun.font.name = 'Calibri'
                hrun.font.size = Pt(13.5)
                hrun.bold = True
                hrun.font.color.rgb = RGBColor(51, 65, 85)
            elif level == 3:
                hp.paragraph_format.space_before = Pt(10)
                hp.paragraph_format.space_after = Pt(4)
                hrun = hp.add_run(heading_text)
                hrun.font.name = 'Calibri'
                hrun.font.size = Pt(11.5)
                hrun.bold = True
                hrun.font.color.rgb = RGBColor(71, 85, 105)
            else:  # H4, H5, H6 (e.g. "Question 1: Multiple Choice")
                hp.paragraph_format.space_before = Pt(8)
                hp.paragraph_format.space_after = Pt(3)
                hrun = hp.add_run(heading_text)
                hrun.font.name = 'Calibri'
                hrun.font.size = Pt(10.5)
                hrun.bold = True
                hrun.font.color.rgb = RGBColor(15, 23, 42)
            i += 1
            continue

        # Bullet lists (- , * , + )
        if stripped.startswith(("- ", "* ", "+ ")):
            bullet_text = stripped[2:].strip()
            bp = doc.add_paragraph(style='List Bullet')
            bp.paragraph_format.space_after = Pt(3)
            bp.paragraph_format.line_spacing = 1.15
            # Add runs
            parts = re.split(r'(\*\*.*?\*\*|\*.*?\*|`.*?`)', bullet_text)
            for part in parts:
                if not part:
                    continue
                if part.startswith('**') and part.endswith('**'):
                    r = bp.add_run(part[2:-2])
                    r.bold = True
                elif part.startswith('*') and part.endswith('*'):
                    r = bp.add_run(part[1:-1])
                    r.italic = True
                elif part.startswith('`') and part.endswith('`'):
                    r = bp.add_run(part[1:-1])
                    r.font.name = 'Consolas'
                else:
                    bp.add_run(part)
            i += 1
            continue

        # Numbered lists (1. , 2) , A) , B) )
        list_match = re.match(r'^([0-9]+[\.\)]|[A-Z][\.\)])\s+(.*)$', stripped)
        if list_match:
            prefix = list_match.group(1)
            item_text = list_match.group(2).strip()
            lp = doc.add_paragraph()
            lp.paragraph_format.left_indent = Inches(0.25)
            lp.paragraph_format.space_after = Pt(3)
            lp.paragraph_format.line_spacing = 1.15
            p_run = lp.add_run(f"{prefix} ")
            p_run.bold = True
            
            parts = re.split(r'(\*\*.*?\*\*|\*.*?\*|`.*?`)', item_text)
            for part in parts:
                if not part:
                    continue
                if part.startswith('**') and part.endswith('**'):
                    r = lp.add_run(part[2:-2])
                    r.bold = True
                elif part.startswith('*') and part.endswith('*'):
                    r = lp.add_run(part[1:-1])
                    r.italic = True
                elif part.startswith('`') and part.endswith('`'):
                    r = lp.add_run(part[1:-1])
                    r.font.name = 'Consolas'
                else:
                    lp.add_run(part)
            i += 1
            continue

        # Standard Body Paragraph
        add_styled_paragraph(doc, stripped, space_after=4)
        i += 1

    # Defensive recovery: If document had an unclosed code block (e.g. from splitting or prompt output)
    if in_code_block and code_lines:
        is_md_block = code_block_lang in ["markdown", "md", ""] or any(l.strip().startswith(("#", "##", "- ", "* ", "1.", "A)")) for l in code_lines[:8])
        if is_md_block:
            for cl in code_lines:
                cl_stripped = cl.strip()
                if not cl_stripped:
                    continue
                # Heading
                h_match = re.match(r"^(#{1,6})\s+(.*)$", cl_stripped)
                if h_match:
                    h_level = len(h_match.group(1))
                    h_text = h_match.group(2).strip()
                    hp = doc.add_paragraph()
                    hp.paragraph_format.space_before = Pt(12)
                    hp.paragraph_format.space_after = Pt(4)
                    hp.paragraph_format.keep_with_next = True
                    hr = hp.add_run(h_text)
                    hr.bold = True
                    hr.font.name = 'Calibri'
                    hr.font.size = Pt(15 if h_level == 1 else (13 if h_level == 2 else 11.5))
                    hr.font.color.rgb = RGBColor(30, 58, 138) if h_level == 1 else RGBColor(51, 65, 85)
                    continue
                # Bullet
                if cl_stripped.startswith(("- ", "* ", "+ ")):
                    bp = doc.add_paragraph(style='List Bullet')
                    bp.paragraph_format.space_after = Pt(3)
                    add_styled_paragraph(doc, cl_stripped[2:])
                    continue
                # Numbered / lettered list
                num_match = re.match(r"^([0-9]+[\.\)]|[A-Z][\.\)])\s+(.*)$", cl_stripped)
                if num_match:
                    np_para = doc.add_paragraph()
                    np_para.paragraph_format.space_after = Pt(4)
                    prefix_run = np_para.add_run(num_match.group(1) + " ")
                    prefix_run.bold = True
                    prefix_run.font.name = 'Calibri'
                    prefix_run.font.size = Pt(10.5)
                    add_styled_paragraph(doc, num_match.group(2))
                    continue
                # Normal paragraph
                add_styled_paragraph(doc, cl_stripped, space_after=4)
        else:
            tbl = doc.add_table(rows=1, cols=1)
            tbl.alignment = WD_TABLE_ALIGNMENT.CENTER
            cell = tbl.cell(0, 0)
            cell.width = Inches(6.5)
            set_cell_background(cell, "F8FAFC")
            set_cell_margins(cell, top=120, bottom=120, left=180, right=180)
            cp = cell.paragraphs[0]
            cp.paragraph_format.space_after = Pt(0)
            c_run = cp.add_run("\n".join(code_lines))
            c_run.font.name = 'Consolas'
            c_run.font.size = Pt(9.0)
            c_run.font.color.rgb = RGBColor(15, 23, 42)

    doc.save(str(file_path))
    docx_url = f"/api/generated-media/{file_path.name}"
    return docx_url, file_path
